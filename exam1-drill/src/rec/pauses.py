# Measures the pauses in every narration clip (ffmpeg silencedetect) and writes clip_pauses.js:
# CLIP_PAUSES["q-L20-033"] = [duration, s1, e1, s2, e2, ...] in seconds. At playback the app matches these
# pauses to the sentences on screen, so the highlight moves when the narrator reaches each sentence.
# Run after recording new clips: python3 rec/pauses.py  (from exam1-drill/src)
import os, re, json, subprocess, concurrent.futures as cf
HERE = os.path.dirname(os.path.abspath(__file__)); AUD = os.path.join(HERE, '..', '..', 'audio'); OUT = os.path.join(HERE, '..', 'clip_pauses.js')
def one(f):
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', os.path.join(AUD, f), '-af', 'silencedetect=noise=-35dB:d=0.12', '-f', 'null', '-'], capture_output=True, text=True)
    e = r.stderr; m = re.search(r'Duration: (\d+):(\d+):([\d.]+)', e)
    if not m: return f, None
    dur = int(m[1]) * 3600 + int(m[2]) * 60 + float(m[3])
    s = [float(x) for x in re.findall(r'silence_start: ([\d.]+)', e)]; en = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', e)]
    out = [round(dur, 2)]
    for a, b in zip(s, en): out += [round(a, 2), round(b, 2)]
    return f, out
files = sorted(f for f in os.listdir(AUD) if f.endswith('.mp3'))
res = {}
with cf.ThreadPoolExecutor(8) as ex:
    for f, v in ex.map(one, files):
        if v: res[f[:-4]] = v
open(OUT, 'w').write('// generated by rec/pauses.py: per clip [duration, pause start, pause end, ...] in seconds\nconst CLIP_PAUSES = ' + json.dumps(res, separators=(',', ':')) + ';\n')
print(len(res), 'clips', os.path.getsize(OUT), 'bytes')

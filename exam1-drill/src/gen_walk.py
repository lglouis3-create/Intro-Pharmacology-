"""Guide walkthroughs: walk/<section id>.json (spoken scripts in segments, each tied to a deck slide or a reading)
and walk/decks.json (deck names and slide counts) -> guide_walk.js. Slide images live in ../slides/<deck>-NN.jpg."""
import json, os, glob, re
HERE = os.path.dirname(os.path.abspath(__file__))
decks = json.load(open(os.path.join(HERE, 'walk', 'decks.json')))
walk = {}
for f in sorted(glob.glob(os.path.join(HERE, 'walk', 'guide3-*.json'))):
    w = json.load(open(f)); sid = w['id']
    assert os.path.basename(f) == sid + '.json', f
    segs = []
    for s in w['segs']:
        t = re.sub(r'\s+', ' ', s['text']).strip(); assert t, (sid, 'empty segment')
        sl = s.get('slide') or None
        if sl:
            d, n = sl.split(':'); assert d in decks and 1 <= int(n) <= decks[d]['n'], (sid, sl)
            assert os.path.exists(os.path.join(HERE, '..', 'slides', '%s-%02d.jpg' % (d, int(n)))), (sid, sl)
        rd = s.get('reading') or None
        if rd: assert os.path.exists(os.path.join(HERE, 'readings', rd + '.json')), (sid, rd)
        segs.append({'t': t, 's': sl, 'r': rd})
    words = sum(len(s['t'].split()) for s in segs)
    walk[sid] = {'title': w['title'], 'segs': segs, 'mins': max(1, round(words / 150))}
open(os.path.join(HERE, 'guide_walk.js'), 'w').write('// generated by gen_walk.py from walk/*.json\nconst GW_DECKS = ' + json.dumps(decks) + ';\nconst GUIDE_WALK = ' + json.dumps(walk, ensure_ascii=False) + ';\n')
print('guide_walk.js:', len(walk), 'walkthroughs,', sum(len(w['segs']) for w in walk.values()), 'segments')
